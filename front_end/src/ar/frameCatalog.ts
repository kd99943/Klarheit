function normalizeProductName(name: string): string {
  return name.trim().toUpperCase().replace(/\s+/g, " ");
}

/** Parse "54-17-140" specs into fit numbers. */
export function parseSpecsSize(specsSize?: string | null) {
  if (!specsSize) return null;
  const parts = specsSize.split(/[-–—]/).map((p) => Number(p.trim()));
  if (parts.length < 3 || parts.some((n) => !Number.isFinite(n))) return null;
  return { lens: parts[0], bridge: parts[1], temple: parts[2] };
}

export function getSpecsForProduct(product: Product) {
  const parsed = parseSpecsSize(product.specsSize);
  const fallback = PRODUCT_SPECS[normalizeProductName(product.name)] ?? PRODUCT_SPECS["AERO X1"];
  if (!parsed) return fallback;
  return {
    ...fallback,
    lens: parsed.lens,
    bridge: parsed.bridge,
    temple: parsed.temple,
  };
}

export function getSpecsForProductName(name: string) {
  return PRODUCT_SPECS[normalizeProductName(name)] ?? PRODUCT_SPECS["AERO X1"];
}

/**
 * Resolve AR frame config for a product, optionally selecting a backend finish.
 * Backend arConfigs supply finish colors; local map supplies the silhouette style.
 */
export function getFrameConfigForProduct(
  product: Product,
  finishId?: ARFinishId | null
): ARFrameConfig {
  const nameUpper = normalizeProductName(product.name);
  const styleConfig = FRAME_STYLES_MAP[nameUpper] || FRAME_STYLES_MAP["AERO X1"];
  const finishes = product.arConfigs ?? [];

  const defaultFinish = finishes.find((f) => f.id === "titanium") || finishes[0] || null;
  const backendFinish = (finishId && finishes.find((f) => f.id === finishId)) || defaultFinish;
  const specs = getSpecsForProduct(product);

  // Prefer product-photo colors for default; backend finish overrides when selected
  const frameColor = backendFinish?.frameColor ?? styleConfig.frameColor;
  const lensColor = backendFinish?.lensColor ?? styleConfig.lensColor;
  // Keep sun lenses dark even if backend has a light default for crystal frames
  const isSun = styleConfig.styleName === "crystal-sun";
  const resolvedLensColor = isSun && !finishId ? styleConfig.lensColor : lensColor;

  // A finish can supply its own asset or reuse the default asset with a new color.
  // Units and material policy belong to the asset owner, not the selected finish.
  const modelOwner = backendFinish?.modelUrl ? backendFinish : defaultFinish?.modelUrl ? defaultFinish : null;
  const modelUrl = modelOwner?.modelUrl ?? FRAME_MODEL_URLS[nameUpper] ?? null;

  return {
    id: backendFinish?.id ?? product.name.toLowerCase().replace(/\s+/g, "-"),
    productName: product.name,
    finishLabelKey: backendFinish?.finishLabelKey ?? `color.${product.name.toLowerCase().replace(/\s+/g, "")}`,
    lensLabel: backendFinish?.lensLabel ?? styleConfig.lensLabel,
    fitLabelKey: backendFinish?.fitLabelKey ?? "fit.urbanContrast",
    frameColor,
    lensColor: resolvedLensColor,
    modelUrl,
    modelScaleMode: modelOwner?.modelScaleMode ?? "normalized",
    legacyMaterials: modelOwner?.legacyMaterials ?? (!!modelUrl && Object.values(FRAME_MODEL_URLS).includes(modelUrl)),
    lensCenterDistanceMm: specs.lens + specs.bridge,
    styleName: styleConfig.styleName,
    transformOffset: {
      position: (backendFinish?.transformOffset?.position as [number, number, number]) ?? [0, -0.028, 0],
      rotation: (backendFinish?.transformOffset?.rotation as [number, number, number]) ?? [0, 0, 0],
      scale: backendFinish?.transformOffset?.scale ?? 1,
    },
  };
}
